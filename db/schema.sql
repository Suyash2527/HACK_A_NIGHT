GRANT SELECT, INSERT ON chain_txs TO app_anchor;
GRANT UPDATE (status, block_number, error, confirmed_at) ON chain_txs TO app_anchor;
GRANT SELECT, INSERT ON merkle_batches TO app_anchor;
GRANT UPDATE (status, tx_hash, anchored_at) ON merkle_batches TO app_anchor;
GRANT UPDATE (batch_id, merkle_proof, anchor_tx, anchored_at) ON documents TO app_anchor;
GRANT UPDATE (tx_hash) ON case_manifests TO app_anchor;

RESET ROLE;
