-- Sakshya database schema (PostgreSQL 17 on Amazon RDS; also runs on PGlite for tests).
-- Security model:
--   * Tables are owned by NOLOGIN role app_owner; the web app connects as app_user (non-owner) with FORCE ROW LEVEL SECURITY.
--   * Every request runs in a transaction that first does  SELECT set_config('app.user_id', <cognito sub>, true)
--     (txn-local, so it cannot leak across pooled connections). Policies key on app.app_uid().
--   * Evidence tables are APPEND-ONLY: triggers reject UPDATE/DELETE (only app_anchor may fill anchor columns once).
--   * audit_log is a hash chain computed INSIDE the database (entry_hash covers the legal basis), so the app cannot forge it.
-- Run as a superuser/admin once:  psql -f db/schema.sql   (idempotent only on a fresh database)

SET check_function_bodies = off;

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_owner')  THEN CREATE ROLE app_owner NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_user')   THEN CREATE ROLE app_user NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_anchor') THEN CREATE ROLE app_anchor NOLOGIN; END IF;
END $$;

-- On Amazon RDS the admin user is not a true superuser: it must be allowed to SET ROLE app_owner (PostgreSQL 16+ syntax).
DO $$ BEGIN
  EXECUTE format('GRANT app_owner TO %I WITH ADMIN OPTION, INHERIT TRUE, SET TRUE', current_user);
EXCEPTION WHEN others THEN NULL;   -- already a member / superuser: nothing to do
END $$;

CREATE SCHEMA IF NOT EXISTS app AUTHORIZATION app_owner;
GRANT USAGE ON SCHEMA app TO app_user, app_anchor;
SET ROLE app_owner;
SET search_path = app, pg_catalog;

-- ───────────────────────────── enums
CREATE TYPE user_role AS ENUM ('POLICE','FORENSIC_LAB','PUBLIC_PROSECUTOR','JUDGE','ADMIN','DEFENCE_ADVOCATE','COMPLAINANT');
CREATE TYPE doc_type AS ENUM ('FIR','WITNESS_STATEMENT','FORENSIC_REPORT','CHARGE_SHEET');
CREATE TYPE case_stage AS ENUM ('FIR_REGISTERED','INVESTIGATION','FORENSIC_ANALYSIS','CHARGE_SHEET_FILED','TRIAL','JUDGMENT','CLOSED');
-- order mirrors types/api.ts AUDIT_ACTIONS and the on-chain enum
CREATE TYPE audit_action AS ENUM ('UPLOAD','VIEW','DOWNLOAD','VERIFY','DENIED','ANCHOR','SCAN','TAMPER_DETECTED','RESTORE',
  'REQUEST_FILED','REQUEST_GRANTED','REQUEST_REJECTED','FOLDER_ASSEMBLED','MILESTONE_ADDED','MANIFEST_SEALED');

-- ───────────────────────────── tables
CREATE TABLE users (
  id          uuid PRIMARY KEY,                 -- Cognito sub
  email       text NOT NULL UNIQUE,
  name        text NOT NULL,
  role        user_role NOT NULL,
  station     text NOT NULL DEFAULT '',
  station_code text CHECK (station_code ~ '^[A-Z]{2,4}$'),   -- short code used in FIR numbers, e.g. GNG
  clearance   int  NOT NULL DEFAULT 1 CHECK (clearance BETWEEN 0 AND 5),
  dsa_public_key_hash text,                     -- sha256 of the user's ML-DSA-65 public key (hex)
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE cases (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  fir_no        text NOT NULL UNIQUE,
  station       text NOT NULL,
  stage         case_stage NOT NULL DEFAULT 'FIR_REGISTERED',
  status        text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED')),
  created_by    uuid NOT NULL REFERENCES users(id),
  complainant_id uuid REFERENCES users(id),
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE case_assignments (
  case_id  uuid NOT NULL REFERENCES cases(id),
  user_id  uuid NOT NULL REFERENCES users(id),
  role     user_role NOT NULL,
  PRIMARY KEY (case_id, user_id)
);

CREATE TABLE documents (
  id            uuid PRIMARY KEY,               -- generated by the app BEFORE insert (needed for AAD + leaf)
  case_id       uuid NOT NULL REFERENCES cases(id),
  type          doc_type NOT NULL,
  version       int  NOT NULL CHECK (version >= 1),
  parent_id     uuid REFERENCES documents(id),
  filename      text NOT NULL,
  mime_type     text NOT NULL,
  size_bytes    bigint NOT NULL CHECK (size_bytes >= 0),
  uploader_id   uuid NOT NULL REFERENCES users(id),
  sha256        text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  chunk_root    text NOT NULL CHECK (chunk_root ~ '^[0-9a-f]{64}$'),
  chunk_leaves  jsonb NOT NULL,
  part_root     text NOT NULL CHECK (part_root ~ '^[0-9a-f]{64}$'),
  part_count    int  NOT NULL CHECK (part_count >= 1),
  wrapped_dek   jsonb NOT NULL,                 -- ML-KEM-768 wrapped file key (never the key itself)
  signature     text NOT NULL,                  -- ML-DSA-65, base64
  signed_payload text NOT NULL,                 -- exact canonical JSON that was signed
  signer_key_hash text NOT NULL CHECK (signer_key_hash ~ '^[0-9a-f]{64}$'),
  created_at    timestamptz NOT NULL DEFAULT now(),
  -- filled once by app_anchor:
  batch_id      bigint,
  merkle_proof  jsonb,
  anchor_tx     text,
  anchored_at   timestamptz,
  UNIQUE (case_id, id)
);
CREATE INDEX documents_case_idx ON documents(case_id, created_at);

CREATE TABLE document_parts (
  doc_id   uuid NOT NULL REFERENCES documents(id),
  idx      int  NOT NULL CHECK (idx >= 0),
  address  text NOT NULL CHECK (address ~ '^[0-9a-f]{64}$'),   -- sha256 of the stored encrypted object = storage key
  size     int  NOT NULL CHECK (size > 0),
  PRIMARY KEY (doc_id, idx)
);

CREATE TABLE case_manifests (
  case_id   uuid NOT NULL REFERENCES cases(id),
  version   int  NOT NULL CHECK (version >= 1),
  root      text NOT NULL CHECK (root ~ '^[0-9a-f]{64}$'),
  doc_count int  NOT NULL CHECK (doc_count >= 1),
  tx_hash   text,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (case_id, version)
);

CREATE TABLE merkle_batches (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,   -- == on-chain batchId
  root        text NOT NULL CHECK (root ~ '^[0-9a-f]{64}$'),
  doc_count   int  NOT NULL CHECK (doc_count >= 1),
  signature   text NOT NULL,                    -- system ML-DSA-65 over canonical batch payload
  signature_hash text NOT NULL CHECK (signature_hash ~ '^[0-9a-f]{64}$'),
  tx_hash     text,
  status      text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed')),
  created_at  timestamptz NOT NULL DEFAULT now(),
  anchored_at timestamptz
);

CREATE TABLE milestones (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  case_id     uuid NOT NULL REFERENCES cases(id),
  stage       case_stage NOT NULL,
  note        text,
  recorded_by uuid NOT NULL REFERENCES users(id),
  at          timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE document_requests (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  case_id      uuid NOT NULL REFERENCES cases(id),
  requester_id uuid NOT NULL REFERENCES users(id),
  document_ids uuid[] NOT NULL CHECK (cardinality(document_ids) >= 1),
  legal_basis  jsonb NOT NULL,
  reason       text NOT NULL CHECK (length(btrim(reason)) > 0),
  filed_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE request_decisions (
  request_id   uuid PRIMARY KEY REFERENCES document_requests(id),   -- one decision per request
  decided_by   uuid NOT NULL REFERENCES users(id),
  decision     text NOT NULL CHECK (decision IN ('GRANT','REJECT')),
  order_ref    text NOT NULL CHECK (length(btrim(order_ref)) > 0),
  note         text NOT NULL,
  granted_document_ids uuid[] NOT NULL DEFAULT '{}',
  expires_at   timestamptz,
  decided_at   timestamptz NOT NULL DEFAULT now(),
  CHECK ((decision = 'GRANT' AND cardinality(granted_document_ids) >= 1) OR (decision = 'REJECT' AND cardinality(granted_document_ids) = 0))
);

CREATE TABLE request_grants (                   -- created ONLY by the decision trigger below
  request_id  uuid NOT NULL REFERENCES document_requests(id),
  document_id uuid NOT NULL REFERENCES documents(id),
  user_id     uuid NOT NULL REFERENCES users(id),
  order_ref   text NOT NULL,
  expires_at  timestamptz,
  PRIMARY KEY (request_id, document_id)
);

-- FIR numbers are assigned ONLY by create_case(): gapless serial per (station, year) + a chain-derived verification code.
CREATE TABLE fir_counters (
  station_code text NOT NULL,
  year         int  NOT NULL,
  last_serial  int  NOT NULL DEFAULT 0,
  PRIMARY KEY (station_code, year)
);
CREATE TABLE fir_register (                       -- append-only, hash-chained register of every FIR ever issued
  seq          bigint PRIMARY KEY,
  fir_no       text NOT NULL UNIQUE,
  station_code text NOT NULL,
  year         int  NOT NULL,
  serial       int  NOT NULL,
  case_id      uuid NOT NULL REFERENCES cases(id),
  issued_by    uuid NOT NULL REFERENCES users(id),
  issued_at    timestamptz NOT NULL,
  prev_hash    text NOT NULL,
  entry_hash   text NOT NULL UNIQUE,
  UNIQUE (station_code, year, serial)
);

CREATE TABLE verification_results (               -- latest-first history of integrity checks (append-only)
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  doc_id     uuid NOT NULL REFERENCES documents(id),
  status     text NOT NULL CHECK (status IN ('VERIFIED','TAMPERED','PENDING_ANCHOR','UNANCHORED','ERROR')),
  result     jsonb NOT NULL,                       -- the full VerifyResult served to the UI
  checked_by uuid NOT NULL REFERENCES users(id),
  at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX verification_doc_idx ON verification_results(doc_id, at DESC);

CREATE TABLE chain_txs (                          -- every blockchain transaction the backend sends (the "live feed")
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  kind         text NOT NULL CHECK (kind IN ('REGISTER_RECORD','ATTEST_SIGNATURE','SEAL_MANIFEST','AUDIT_EVENT','ANCHOR_BATCH')),
  tx_hash      text NOT NULL UNIQUE CHECK (tx_hash ~ '^0x[0-9a-f]{64}$'),
  chain_id     bigint NOT NULL,
  doc_id       uuid REFERENCES documents(id),
  case_id      uuid REFERENCES cases(id),
  label        text NOT NULL,
  status       text NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted','confirmed','failed')),
  block_number bigint,
  error        text,
  created_at   timestamptz NOT NULL DEFAULT now(),
  confirmed_at timestamptz
);
CREATE INDEX chain_txs_doc_idx ON chain_txs(doc_id, created_at DESC);
CREATE INDEX chain_txs_case_idx ON chain_txs(case_id, created_at DESC);

CREATE TABLE audit_log (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  seq         bigint NOT NULL UNIQUE,
  actor_id    uuid NOT NULL REFERENCES users(id),
  action      audit_action NOT NULL,
  doc_id      uuid,
  case_id     uuid,
  at          timestamptz NOT NULL,
  legal_basis jsonb NOT NULL,
  detail      text,
  prev_hash   text NOT NULL,
  entry_hash  text NOT NULL UNIQUE,
  CHECK (legal_basis ? 'code'),
  CHECK (legal_basis->>'code' IN ('INVESTIGATION','FORENSIC_ASSIGNMENT','PROSECUTION_ASSIGNMENT','JUDICIAL_AUTHORITY','COURT_ORDER','STATUTORY_DISCLOSURE','VICTIM_INFORMATION','SYSTEM_INTEGRITY')),
  CHECK (legal_basis->>'code' NOT IN ('COURT_ORDER','STATUTORY_DISCLOSURE')
         OR (length(btrim(coalesce(legal_basis->>'citation',''))) > 0
             AND (legal_basis->>'code' <> 'COURT_ORDER' OR length(btrim(coalesce(legal_basis->>'orderRef',''))) > 0)))
);
CREATE INDEX audit_doc_idx ON audit_log(doc_id, seq);
CREATE INDEX audit_case_idx ON audit_log(case_id, seq);

-- ───────────────────────────── identity helpers
CREATE FUNCTION app_uid() RETURNS uuid LANGUAGE sql STABLE SET search_path = pg_catalog, app AS
$$ SELECT nullif(current_setting('app.user_id', true), '')::uuid $$;   -- '' (not NULL) after a txn ends on a reused connection

CREATE FUNCTION app_role() RETURNS user_role LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, app AS
$$ SELECT role FROM app.users WHERE id = app.app_uid() $$;

CREATE FUNCTION is_court() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, app AS
$$ SELECT coalesce(app.app_role() IN ('JUDGE','ADMIN'), false) $$;

CREATE FUNCTION is_assigned(p_case uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, app AS
$$ SELECT EXISTS (SELECT 1 FROM app.case_assignments WHERE case_id = p_case AND user_id = app.app_uid()) $$;

CREATE FUNCTION is_complainant(p_case uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, app AS
$$ SELECT EXISTS (SELECT 1 FROM app.cases WHERE id = p_case AND complainant_id = app.app_uid()) $$;

CREATE FUNCTION has_grant(p_doc uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, app AS
$$ SELECT EXISTS (SELECT 1 FROM app.request_grants g
                  WHERE g.document_id = p_doc AND g.user_id = app.app_uid() AND (g.expires_at IS NULL OR g.expires_at > now())) $$;

-- Evidence visibility: court roles, assigned officers/labs/prosecutors, or an unexpired court grant. Complainants never.
CREATE FUNCTION can_read_doc(p_doc uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, app AS
$$ SELECT app.is_court()
       OR EXISTS (SELECT 1 FROM app.documents d WHERE d.id = p_doc AND app.is_assigned(d.case_id))
       OR app.has_grant(p_doc) $$;

-- Court-granted access lets an advocate see the CASE HEADER (not other documents) for cases where they hold a live grant.
CREATE FUNCTION has_case_grant(p_case uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, app AS
$$ SELECT EXISTS (SELECT 1 FROM app.request_grants g JOIN app.documents d ON d.id = g.document_id
                  WHERE d.case_id = p_case AND g.user_id = app.app_uid() AND (g.expires_at IS NULL OR g.expires_at > now())) $$;

-- What an advocate may LOOK UP before asking the court: identifiers and titles only — never content, hashes or custody.
CREATE FUNCTION request_catalog(p_fir_no text)
RETURNS TABLE (case_id uuid, fir_no text, station text, stage case_stage, doc_id uuid, doc_type doc_type, filename text, version int, created_at timestamptz)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = pg_catalog, app AS $$
BEGIN
  IF app.app_role() NOT IN ('DEFENCE_ADVOCATE','JUDGE','ADMIN') THEN RAISE EXCEPTION 'insufficient_privilege' USING ERRCODE = '42501'; END IF;
  RETURN QUERY SELECT c.id, c.fir_no, c.station, c.stage, d.id, d.type, d.filename, d.version, d.created_at
               FROM app.cases c JOIN app.documents d ON d.case_id = c.id WHERE c.fir_no = p_fir_no ORDER BY d.created_at, d.id;
END $$;

-- Role → document type matrix (mirrors ROLE_UPLOAD_TYPES in types/api.ts)
CREATE FUNCTION can_upload(t doc_type) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, app AS
$$ SELECT CASE app.app_role()
     WHEN 'POLICE' THEN t IN ('FIR','WITNESS_STATEMENT')
     WHEN 'FORENSIC_LAB' THEN t = 'FORENSIC_REPORT'
     WHEN 'PUBLIC_PROSECUTOR' THEN t = 'CHARGE_SHEET'
     ELSE false END $$;

-- Login lookup: runs BEFORE any identity exists, so it cannot rely on RLS. Exposes only what a sign-in needs.
CREATE FUNCTION find_user_by_email(p_email text) RETURNS TABLE (id uuid, name text, email text, role user_role, station text, clearance int)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, app AS
$$ SELECT u.id, u.name, u.email, u.role, u.station, u.clearance FROM app.users u WHERE lower(u.email) = lower(p_email) $$;

-- ───────────────────────────── audit hash chain (computed in the database)
CREATE FUNCTION audit_entry_hash(p_seq bigint, p_prev text, p_actor uuid, p_action audit_action, p_doc uuid, p_case uuid,
                                 p_at timestamptz, p_basis jsonb, p_detail text) RETURNS text
LANGUAGE sql IMMUTABLE SET search_path = pg_catalog AS
$$ SELECT encode(sha256(convert_to(concat_ws('|', p_seq::text, p_prev, p_actor::text, p_action::text,
       coalesce(p_doc::text,''), coalesce(p_case::text,''),
       to_char(p_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'), p_basis::text, coalesce(p_detail,'')), 'UTF8')), 'hex') $$;

CREATE FUNCTION audit_chain_before_insert() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, app AS $$
DECLARE v_prev text; v_seq bigint;
BEGIN
  PERFORM pg_advisory_xact_lock(727001);        -- serialise chain growth
  SELECT entry_hash, seq INTO v_prev, v_seq FROM app.audit_log ORDER BY seq DESC LIMIT 1;
  NEW.seq := coalesce(v_seq, 0) + 1;
  NEW.prev_hash := coalesce(v_prev, repeat('0', 64));
  NEW.at := clock_timestamp();
  NEW.entry_hash := app.audit_entry_hash(NEW.seq, NEW.prev_hash, NEW.actor_id, NEW.action, NEW.doc_id, NEW.case_id, NEW.at, NEW.legal_basis, NEW.detail);
  RETURN NEW;
END $$;
CREATE TRIGGER audit_chain BEFORE INSERT ON audit_log FOR EACH ROW EXECUTE FUNCTION audit_chain_before_insert();

/** Recomputes the whole chain. Returns (checked, first_broken_id). Court roles only. */
CREATE FUNCTION verify_audit_chain(OUT checked bigint, OUT first_broken_id uuid, OUT head_hash text)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = pg_catalog, app AS $$
DECLARE r record; v_prev text := repeat('0', 64); v_expected_seq bigint := 1;
BEGIN
  IF NOT app.is_court() THEN RAISE EXCEPTION 'insufficient_privilege' USING ERRCODE = '42501'; END IF;
  checked := 0; first_broken_id := NULL;
  FOR r IN SELECT * FROM app.audit_log ORDER BY seq LOOP
    checked := checked + 1;
    IF first_broken_id IS NULL AND (r.seq <> v_expected_seq OR r.prev_hash <> v_prev OR
       r.entry_hash <> app.audit_entry_hash(r.seq, r.prev_hash, r.actor_id, r.action, r.doc_id, r.case_id, r.at, r.legal_basis, r.detail)) THEN
      first_broken_id := r.id;
    END IF;
    v_prev := r.entry_hash; v_expected_seq := v_expected_seq + 1;
  END LOOP;
  head_hash := CASE WHEN checked = 0 THEN NULL ELSE v_prev END;
END $$;

-- ───────────────────────────── append-only guards
CREATE FUNCTION forbid_mutation() RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN RAISE EXCEPTION '% on % is forbidden: append-only', TG_OP, TG_TABLE_NAME USING ERRCODE = '42501'; END $$;

CREATE FUNCTION documents_guard() RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, app AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'DELETE on documents is forbidden: append-only' USING ERRCODE = '42501'; END IF;
  IF current_user <> 'app_anchor' THEN RAISE EXCEPTION 'UPDATE on documents is forbidden: append-only' USING ERRCODE = '42501'; END IF;
  IF (to_jsonb(NEW) - '{batch_id,merkle_proof,anchor_tx,anchored_at}'::text[]) IS DISTINCT FROM (to_jsonb(OLD) - '{batch_id,merkle_proof,anchor_tx,anchored_at}'::text[])
    THEN RAISE EXCEPTION 'app_anchor may only set anchor columns' USING ERRCODE = '42501'; END IF;
  IF OLD.anchor_tx IS NOT NULL THEN RAISE EXCEPTION 'document already anchored' USING ERRCODE = '42501'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER documents_append_only BEFORE UPDATE OR DELETE ON documents FOR EACH ROW EXECUTE FUNCTION documents_guard();

CREATE TRIGGER fir_register_append_only BEFORE UPDATE OR DELETE ON fir_register FOR EACH ROW EXECUTE FUNCTION forbid_mutation();
CREATE TRIGGER parts_append_only      BEFORE UPDATE OR DELETE ON document_parts   FOR EACH ROW EXECUTE FUNCTION forbid_mutation();
CREATE TRIGGER audit_append_only      BEFORE UPDATE OR DELETE ON audit_log        FOR EACH ROW EXECUTE FUNCTION forbid_mutation();
CREATE TRIGGER verification_append_only BEFORE UPDATE OR DELETE ON verification_results FOR EACH ROW EXECUTE FUNCTION forbid_mutation();
CREATE TRIGGER milestones_append_only BEFORE UPDATE OR DELETE ON milestones       FOR EACH ROW EXECUTE FUNCTION forbid_mutation();
CREATE TRIGGER requests_append_only   BEFORE UPDATE OR DELETE ON document_requests FOR EACH ROW EXECUTE FUNCTION forbid_mutation();
CREATE TRIGGER decisions_append_only  BEFORE UPDATE OR DELETE ON request_decisions FOR EACH ROW EXECUTE FUNCTION forbid_mutation();
CREATE TRIGGER grants_append_only     BEFORE UPDATE OR DELETE ON request_grants   FOR EACH ROW EXECUTE FUNCTION forbid_mutation();
CREATE FUNCTION manifests_guard() RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, app AS $$
BEGIN
  IF TG_OP = 'DELETE' OR current_user <> 'app_anchor' THEN RAISE EXCEPTION '% on case_manifests is forbidden: append-only', TG_OP USING ERRCODE = '42501'; END IF;
  IF OLD.tx_hash IS NOT NULL OR (to_jsonb(NEW) - 'tx_hash') IS DISTINCT FROM (to_jsonb(OLD) - 'tx_hash')
    THEN RAISE EXCEPTION 'app_anchor may only set tx_hash once' USING ERRCODE = '42501'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER manifests_append_only  BEFORE UPDATE OR DELETE ON case_manifests   FOR EACH ROW EXECUTE FUNCTION manifests_guard();

-- Version lineage: originals are v1; a correction must point at a document in the SAME case with a lower version.
CREATE FUNCTION documents_lineage() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, app AS $$
DECLARE p record;
BEGIN
  IF NEW.parent_id IS NULL THEN
    IF NEW.version <> 1 THEN RAISE EXCEPTION 'an original document must be version 1'; END IF;
  ELSE
    SELECT case_id, version INTO p FROM app.documents WHERE id = NEW.parent_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'parent document not found'; END IF;
    IF p.case_id <> NEW.case_id THEN RAISE EXCEPTION 'parent belongs to a different case'; END IF;
    IF NEW.version <= p.version THEN RAISE EXCEPTION 'version must exceed the parent version'; END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER documents_lineage BEFORE INSERT ON documents FOR EACH ROW EXECUTE FUNCTION documents_lineage();

-- A GRANT decision expands into per-document grants; only requested documents of the request's case can be granted.
CREATE FUNCTION decision_expand() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, app AS $$
DECLARE req record; d uuid;
BEGIN
  SELECT * INTO req FROM app.document_requests WHERE id = NEW.request_id;
  IF NEW.decision = 'GRANT' THEN
    FOREACH d IN ARRAY NEW.granted_document_ids LOOP
      IF NOT (d = ANY (req.document_ids)) THEN RAISE EXCEPTION 'document % was not requested', d; END IF;
      IF NOT EXISTS (SELECT 1 FROM app.documents WHERE id = d AND case_id = req.case_id) THEN RAISE EXCEPTION 'document % is not in the request''s case', d; END IF;
      INSERT INTO app.request_grants (request_id, document_id, user_id, order_ref, expires_at)
        VALUES (NEW.request_id, d, req.requester_id, NEW.order_ref, NEW.expires_at);
    END LOOP;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER decision_expand AFTER INSERT ON request_decisions FOR EACH ROW EXECUTE FUNCTION decision_expand();

-- FIR hash chain: entry_hash covers everything that identifies the FIR; the 4-char verification code in the FIR number is its prefix.
CREATE FUNCTION fir_entry_hash(p_seq bigint, p_prev text, p_station text, p_year int, p_serial int, p_case uuid, p_at timestamptz) RETURNS text
LANGUAGE sql IMMUTABLE SET search_path = pg_catalog AS
$$ SELECT encode(sha256(convert_to(concat_ws('|', p_seq::text, p_prev, p_station, p_year::text, p_serial::text, p_case::text,
       to_char(p_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"')), 'UTF8')), 'hex') $$;

-- Case creation + automatic FIR number (STATION/YEAR/SERIAL/CODE). The officer never types a number.
CREATE FUNCTION create_case(p_complainant uuid DEFAULT NULL) RETURNS TABLE (case_id uuid, fir_no text)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, app AS $$
DECLARE
  v_id uuid := gen_random_uuid(); v_station text; v_name text; v_year int := extract(year FROM (now() AT TIME ZONE 'Asia/Kolkata'))::int;
  v_serial int; v_seq bigint; v_prev text; v_at timestamptz := clock_timestamp(); v_hash text; v_fir text;
BEGIN
  IF app.app_role() IS DISTINCT FROM 'POLICE' THEN RAISE EXCEPTION 'only POLICE may register a case' USING ERRCODE = '42501'; END IF;
  SELECT u.station_code, u.station INTO v_station, v_name FROM app.users u WHERE u.id = app.app_uid();
  IF v_station IS NULL THEN RAISE EXCEPTION 'your user has no police station code; ask an administrator' USING ERRCODE = '42501'; END IF;
  IF p_complainant IS NOT NULL AND NOT EXISTS (SELECT 1 FROM app.users u WHERE u.id = p_complainant AND u.role = 'COMPLAINANT') THEN
    RAISE EXCEPTION 'complainant not found'; END IF;

  PERFORM pg_advisory_xact_lock(727002);                       -- serialise issuing so serials and the chain stay gapless
  INSERT INTO app.fir_counters AS fc (station_code, year, last_serial) VALUES (v_station, v_year, 1)
    ON CONFLICT (station_code, year) DO UPDATE SET last_serial = fc.last_serial + 1 RETURNING fc.last_serial INTO v_serial;
  SELECT r.seq, r.entry_hash INTO v_seq, v_prev FROM app.fir_register r ORDER BY r.seq DESC LIMIT 1;
  v_seq := coalesce(v_seq, 0) + 1; v_prev := coalesce(v_prev, repeat('0', 64));

  v_hash := app.fir_entry_hash(v_seq, v_prev, v_station, v_year, v_serial, v_id, v_at);
  v_fir := v_station || '/' || v_year || '/' || lpad(v_serial::text, 4, '0') || '/' || upper(left(v_hash, 4));

  INSERT INTO app.cases (id, fir_no, station, created_by, complainant_id) VALUES (v_id, v_fir, v_name, app.app_uid(), p_complainant);
  INSERT INTO app.fir_register (seq, fir_no, station_code, year, serial, case_id, issued_by, issued_at, prev_hash, entry_hash)
    VALUES (v_seq, v_fir, v_station, v_year, v_serial, v_id, app.app_uid(), v_at, v_prev, v_hash);
  INSERT INTO app.case_assignments (case_id, user_id, role) VALUES (v_id, app.app_uid(), 'POLICE');
  INSERT INTO app.milestones (case_id, stage, note, recorded_by) VALUES (v_id, 'FIR_REGISTERED', 'FIR registered', app.app_uid());
  RETURN QUERY SELECT v_id, v_fir;
END $$;

/** Anyone signed in can check that an FIR number is genuine: it must exist in the register with a matching verification code. */
CREATE FUNCTION check_fir_number(p_fir text) RETURNS TABLE (genuine boolean, issued_at timestamptz, station_code text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, app AS
$$ SELECT coalesce(r.entry_hash IS NOT NULL
                   AND upper(left(r.entry_hash, 4)) = upper(split_part(p_fir, '/', 4))
                   AND r.entry_hash = app.fir_entry_hash(r.seq, r.prev_hash, r.station_code, r.year, r.serial, r.case_id, r.issued_at), false),
          r.issued_at, r.station_code
   FROM (SELECT 1) AS one LEFT JOIN app.fir_register r ON r.fir_no = upper(p_fir) $$;

/** Recomputes the whole register: contiguous sequence, unbroken chain, matching numbers, gapless serials. Court roles only. */
CREATE FUNCTION verify_fir_register(OUT checked bigint, OUT first_broken_seq bigint, OUT problem text)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = pg_catalog, app AS $$
DECLARE r record; v_prev text := repeat('0', 64); v_expect bigint := 1;
BEGIN
  IF NOT app.is_court() THEN RAISE EXCEPTION 'insufficient_privilege' USING ERRCODE = '42501'; END IF;
  checked := 0; first_broken_seq := NULL; problem := NULL;
  FOR r IN SELECT * FROM app.fir_register ORDER BY seq LOOP
    checked := checked + 1;
    IF first_broken_seq IS NULL THEN
      IF r.seq <> v_expect THEN first_broken_seq := r.seq; problem := 'missing register entry';
      ELSIF r.prev_hash <> v_prev THEN first_broken_seq := r.seq; problem := 'chain link broken';
      ELSIF r.entry_hash <> app.fir_entry_hash(r.seq, r.prev_hash, r.station_code, r.year, r.serial, r.case_id, r.issued_at) THEN first_broken_seq := r.seq; problem := 'entry altered';
      ELSIF r.fir_no <> r.station_code || '/' || r.year || '/' || lpad(r.serial::text, 4, '0') || '/' || upper(left(r.entry_hash, 4)) THEN first_broken_seq := r.seq; problem := 'FIR number does not match its register entry';
      END IF;
    END IF;
    v_prev := r.entry_hash; v_expect := v_expect + 1;
  END LOOP;
  IF first_broken_seq IS NULL THEN
    FOR r IN SELECT g.station_code, g.year, count(*) AS n, max(g.serial) AS mx FROM app.fir_register g GROUP BY g.station_code, g.year LOOP
      IF r.n <> r.mx THEN first_broken_seq := 0; problem := format('serial gap for %s/%s', r.station_code, r.year); EXIT; END IF;
    END LOOP;
  END IF;
END $$;

-- Advancing a case: appends a milestone AND moves cases.stage forward (never backwards). The only way stage changes.
CREATE FUNCTION add_milestone(p_case uuid, p_stage case_stage, p_note text DEFAULT NULL) RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, app AS $$
DECLARE v_id uuid := gen_random_uuid(); v_cur case_stage; v_role user_role := app.app_role();
BEGIN
  IF NOT ((v_role = 'POLICE' AND app.is_assigned(p_case)) OR v_role = 'JUDGE') THEN RAISE EXCEPTION 'insufficient_privilege' USING ERRCODE = '42501'; END IF;
  SELECT stage INTO v_cur FROM app.cases WHERE id = p_case;
  IF v_cur IS NULL THEN RAISE EXCEPTION 'case not found'; END IF;
  IF p_stage < v_cur THEN RAISE EXCEPTION 'a case cannot move backwards from % to %', v_cur, p_stage; END IF;
  INSERT INTO app.milestones (id, case_id, stage, note, recorded_by) VALUES (v_id, p_case, p_stage, p_note, app.app_uid());
  UPDATE app.cases SET stage = p_stage, status = CASE WHEN p_stage = 'CLOSED' THEN 'CLOSED' ELSE status END WHERE id = p_case;
  RETURN v_id;
END $$;

-- Court / prosecution staffing of a case (JUDGE/ADMIN assign labs, prosecutors, advocates).
CREATE FUNCTION assign_user(p_case uuid, p_user uuid) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, app AS $$
DECLARE v_role user_role;
BEGIN
  IF NOT (app.is_court() OR (app.app_role() = 'POLICE' AND app.is_assigned(p_case))) THEN RAISE EXCEPTION 'insufficient_privilege' USING ERRCODE = '42501'; END IF;
  SELECT role INTO v_role FROM app.users WHERE id = p_user;
  IF v_role IS NULL THEN RAISE EXCEPTION 'user not found'; END IF;
  IF v_role IN ('JUDGE','ADMIN','COMPLAINANT','DEFENCE_ADVOCATE') THEN RAISE EXCEPTION '% cannot be assigned as case staff', v_role; END IF;
  INSERT INTO app.case_assignments (case_id, user_id, role) VALUES (p_case, p_user, v_role) ON CONFLICT DO NOTHING;
END $$;

-- ───────────────────────────── row-level security
DO $$ DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['users','cases','case_assignments','documents','document_parts','case_manifests','merkle_batches','milestones','document_requests','request_decisions','request_grants','verification_results','chain_txs','fir_counters','fir_register','audit_log'] LOOP
    EXECUTE format('ALTER TABLE app.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE app.%I FORCE ROW LEVEL SECURITY', t);        -- applies to the owner too
    EXECUTE format('CREATE POLICY owner_all ON app.%I TO app_owner USING (true) WITH CHECK (true)', t);   -- for SECURITY DEFINER helpers
  END LOOP;
END $$;

-- users: any signed-in user may read names/roles (needed for custody timelines); no direct writes
CREATE POLICY users_select ON users FOR SELECT TO app_user USING (app.app_uid() IS NOT NULL);

CREATE POLICY cases_select ON cases FOR SELECT TO app_user
  USING (app.is_court() OR app.is_assigned(id) OR app.is_complainant(id) OR app.has_case_grant(id));
-- no INSERT policy: cases are created through create_case()

CREATE POLICY assignments_select ON case_assignments FOR SELECT TO app_user
  USING (app.is_court() OR user_id = app.app_uid() OR app.is_assigned(case_id));

CREATE POLICY docs_select ON documents FOR SELECT TO app_user USING (app.can_read_doc(id));
CREATE POLICY docs_insert ON documents FOR INSERT TO app_user
  WITH CHECK (uploader_id = app.app_uid() AND app.is_assigned(case_id) AND app.can_upload(type));
CREATE POLICY docs_anchor_select ON documents FOR SELECT TO app_anchor USING (true);
CREATE POLICY docs_anchor_update ON documents FOR UPDATE TO app_anchor USING (anchor_tx IS NULL) WITH CHECK (true);

CREATE POLICY parts_select ON document_parts FOR SELECT TO app_user USING (app.can_read_doc(doc_id));
CREATE POLICY parts_insert ON document_parts FOR INSERT TO app_user
  WITH CHECK (EXISTS (SELECT 1 FROM app.documents d WHERE d.id = doc_id AND d.uploader_id = app.app_uid() AND d.created_at > now() - interval '5 minutes'));

CREATE POLICY manifests_select ON case_manifests FOR SELECT TO app_user USING (app.is_court() OR app.is_assigned(case_id));
CREATE POLICY manifests_insert ON case_manifests FOR INSERT TO app_user WITH CHECK (app.is_assigned(case_id) OR app.is_court());
CREATE POLICY manifests_anchor ON case_manifests FOR SELECT TO app_anchor USING (true);
CREATE POLICY manifests_anchor_update ON case_manifests FOR UPDATE TO app_anchor USING (tx_hash IS NULL) WITH CHECK (true);

CREATE POLICY batches_select ON merkle_batches FOR SELECT TO app_user USING (app.is_court());
CREATE POLICY batches_anchor ON merkle_batches FOR ALL TO app_anchor USING (true) WITH CHECK (true);

CREATE POLICY milestones_select ON milestones FOR SELECT TO app_user
  USING (app.is_court() OR app.is_assigned(case_id) OR app.is_complainant(case_id));

CREATE POLICY requests_select ON document_requests FOR SELECT TO app_user USING (app.is_court() OR requester_id = app.app_uid());
CREATE POLICY requests_insert ON document_requests FOR INSERT TO app_user
  WITH CHECK (requester_id = app.app_uid() AND app.app_role() = 'DEFENCE_ADVOCATE');

CREATE POLICY decisions_select ON request_decisions FOR SELECT TO app_user
  USING (app.is_court() OR EXISTS (SELECT 1 FROM app.document_requests r WHERE r.id = request_id AND r.requester_id = app.app_uid()));
CREATE POLICY decisions_insert ON request_decisions FOR INSERT TO app_user
  WITH CHECK (decided_by = app.app_uid() AND app.app_role() = 'JUDGE');

CREATE POLICY grants_select ON request_grants FOR SELECT TO app_user USING (app.is_court() OR user_id = app.app_uid());

CREATE POLICY verification_select ON verification_results FOR SELECT TO app_user USING (app.can_read_doc(doc_id));
CREATE POLICY verification_insert ON verification_results FOR INSERT TO app_user WITH CHECK (checked_by = app.app_uid() AND app.can_read_doc(doc_id));

CREATE POLICY chain_txs_select ON chain_txs FOR SELECT TO app_user
  USING (app.is_court() OR (doc_id IS NOT NULL AND app.can_read_doc(doc_id)) OR (doc_id IS NULL AND case_id IS NOT NULL AND app.is_assigned(case_id)));
CREATE POLICY chain_txs_anchor ON chain_txs FOR ALL TO app_anchor USING (true) WITH CHECK (true);

CREATE POLICY audit_select ON audit_log FOR SELECT TO app_user
  USING (app.is_court() OR actor_id = app.app_uid() OR (case_id IS NOT NULL AND app.is_assigned(case_id)));
CREATE POLICY audit_insert ON audit_log FOR INSERT TO app_user WITH CHECK (actor_id = app.app_uid());

-- ───────────────────────────── grants (no UPDATE/DELETE anywhere for app_user)
GRANT SELECT ON users, cases, case_assignments, documents, document_parts, case_manifests, merkle_batches, milestones,
      document_requests, request_decisions, request_grants, verification_results, chain_txs, audit_log TO app_user;
GRANT INSERT ON documents, document_parts, case_manifests, document_requests, request_decisions, verification_results, audit_log TO app_user;
GRANT EXECUTE ON FUNCTION create_case(uuid), check_fir_number(text), verify_fir_register(), assign_user(uuid, uuid), verify_audit_chain(), find_user_by_email(text), request_catalog(text), add_milestone(uuid, case_stage, text) TO app_user;
